// fish_group.obj (+ .mtl) → src/fishModels.js: four species, vertex-coloured, head toward +z,
// length 1, simplified for instancing.
// Usage: node tools/fish-convert.mjs fish_group.obj fish_group.mtl > src/fishModels.js
import fs from 'fs';
import * as THREE from 'three';
import { OBJLoader } from 'three/examples/jsm/loaders/OBJLoader.js';
import { mergeGeometries, mergeVertices } from 'three/examples/jsm/utils/BufferGeometryUtils.js';
import { SimplifyModifier } from 'three/examples/jsm/modifiers/SimplifyModifier.js';

const [objFile, mtlFile] = process.argv.slice(2);
const KD = {};
let cur = null;
for (const line of fs.readFileSync(mtlFile, 'utf8').split('\n')) {
  const p = line.trim().split(/\s+/);
  if (p[0] === 'newmtl') cur = p[1];
  if (p[0] === 'Kd' && cur) KD[cur] = p.slice(1, 4).map(Number).map((c) => Math.pow(c, 1 / 2.2)); // Blender linear → display
}
const obj = new OBJLoader().parse(fs.readFileSync(objFile, 'utf8'));
const meshes = {}; obj.traverse((m) => { if (m.isMesh) meshes[m.name] = m; });

/** one mesh → non-indexed geometry with a colour per vertex from its material groups */
function coloured(m) {
  const g = m.geometry.clone(), n = g.attributes.position.count, col = new Float32Array(n * 3);
  const mats = Array.isArray(m.material) ? m.material : [m.material];
  const groups = g.groups.length ? g.groups : [{ start: 0, count: n, materialIndex: 0 }];
  for (const gr of groups) { const c = KD[mats[gr.materialIndex].name] || [1, 1, 1]; for (let i = gr.start; i < gr.start + gr.count; i++) col.set(c, i * 3); }
  const out = new THREE.BufferGeometry();
  out.setAttribute('position', g.attributes.position.clone());
  out.setAttribute('color', new THREE.BufferAttribute(col, 3));
  return out;
}
const SPECIES = {
  tang: { parts: ['Cube', 'Sphere', 'Sphere.001', 'Sphere.002', 'Sphere.003'], target: 700, flip: true },
  clown: { parts: ['Cube.001'], target: 900, flip: true },
  minnow: { parts: ['Cube.002'], target: 260, flip: true },
  snapper: { parts: ['Cube.006'], target: 800, flip: true },
};
const out = {};
for (const [name, sp] of Object.entries(SPECIES)) {
  let g = mergeGeometries(sp.parts.map((p) => coloured(meshes[p])));
  g.computeBoundingBox();
  const bb = g.boundingBox, c = bb.getCenter(new THREE.Vector3()), size = bb.getSize(new THREE.Vector3());
  g.translate(-c.x, -c.y, -c.z);
  // long axis is z in the file; all four face −z there
  if (sp.flip) g.rotateY(Math.PI); // head to +z
  g.scale(1 / size.z, 1 / size.z, 1 / size.z);
  // simplify (needs merged vertices; colours are kept by the modifier)
  g.deleteAttribute('normal');
  g = mergeVertices(g, 1e-4);
  const before = g.attributes.position.count;
  const remove = Math.max(0, before - sp.target);
  if (remove > 0) g = new SimplifyModifier().modify(g, remove);
  if (!g.index) g = mergeVertices(g, 1e-4);
  const P = g.attributes.position, C = g.attributes.color;
  const r3 = (v) => Math.round(v * 1000) / 1000;
  out[name] = {
    p: Array.from(P.array, r3), c: Array.from(C.array, (v) => Math.round(Math.min(1, Math.max(0, v)) * 255)), i: Array.from(g.index.array),
    h: r3(size.y / size.z), w: r3(size.x / size.z),
  };
  console.error(name, before, '→', P.count, 'verts', g.index.count / 3, 'tris', 'h/len', (size.y / size.z).toFixed(2));
}
process.stdout.write(`// Generated by tools/fish-convert.mjs from fish_group.obj: four species, head toward +z, length 1.
// p: positions, c: vertex colours 0..255, i: triangle indices.
export default ${JSON.stringify(out)};
`);
